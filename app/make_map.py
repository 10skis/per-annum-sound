"""Builds static/worldmap.js, the land mask behind the dot-matrix map, from Natural Earth's
public-domain 1:110m land outlines (dev/ne_110m_land.geojson, from
github.com/nvkelso/natural-earth-vector). Run again only if the source or resolution changes:
    .venv/bin/python make_map.py
"""

import json
from pathlib import Path

import numpy as np
from PIL import Image, ImageDraw

HERE = Path(__file__).parent
RES = 2                      # cells per degree
LAT_TOP, LAT_BOTTOM = 84, -60  # Antarctica left off
W, H = 360 * RES, (LAT_TOP - LAT_BOTTOM) * RES

img = Image.new("1", (W, H), 0)
d = ImageDraw.Draw(img)
xy = lambda ring: [((lon + 180) * RES, (LAT_TOP - lat) * RES) for lon, lat in ring]
for f in json.loads((HERE / "dev" / "ne_110m_land.geojson").read_text())["features"]:
    g = f["geometry"]
    polys = [g["coordinates"]] if g["type"] == "Polygon" else g["coordinates"]
    for rings in polys:
        d.polygon(xy(rings[0]), fill=1)
        for hole in rings[1:]:
            d.polygon(xy(hole), fill=0)

# Run-length encode each row: alternating water/land run lengths in base 36, water first.
px = img.load()
rows = []
for y in range(H):
    runs, cur, n = [], 0, 0
    for x in range(W):
        v = px[x, y] and 1
        if v == cur:
            n += 1
        else:
            runs.append(n); cur, n = v, 1
    runs.append(n)
    rows.append(",".join(np.base_repr(r, 36).lower() for r in runs))
js = (f"// Generated by make_map.py from Natural Earth 1:110m land (public domain). Do not edit.\n"
      f"window.WORLD = {{ res: {RES}, latTop: {LAT_TOP}, w: {W}, h: {H}, rows: {json.dumps('/'.join(rows))} }};\n")
(HERE / "static" / "worldmap.js").write_text(js)
print(f"worldmap.js: {W}x{H}, {len(js) // 1024} KB")
