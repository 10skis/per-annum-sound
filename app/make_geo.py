"""Builds static/geo.js, the borders, rivers and lakes drawn over the USA and EUROPE map ranges,
from Natural Earth's public-domain 1:50m data (dev/ne_50m_*.geojson, from
github.com/nvkelso/natural-earth-vector). Lines are clipped to the two ranges, simplified and
stored as tenths of a degree. Run again only if the source or the ranges change:
    .venv/bin/python make_geo.py
"""

import json
from pathlib import Path

HERE = Path(__file__).parent
# The USA and EUROPE ranges from index.html, padded so lines run off the edge rather than stop short
BOXES = [(-132, -58, 20, 56), (-26, 64, 24, 66)]  # lon0, lon1, lat0, lat1
TOL = .06  # simplification tolerance, degrees


def inside(p):
    return any(a <= p[0] <= b and c <= p[1] <= d for a, b, c, d in BOXES)


def simplify(pts):
    """Douglas-Peucker."""
    if len(pts) < 3:
        return pts
    (x0, y0), (x1, y1) = pts[0], pts[-1]
    dx, dy = x1 - x0, y1 - y0
    norm = (dx * dx + dy * dy) ** .5 or 1e-9
    far, idx = 0, 0
    for i in range(1, len(pts) - 1):
        d = abs(dy * pts[i][0] - dx * pts[i][1] + x1 * y0 - y1 * x0) / norm
        if d > far:
            far, idx = d, i
    if far <= TOL:
        return [pts[0], pts[-1]]
    return simplify(pts[:idx + 1])[:-1] + simplify(pts[idx:])


def lines(geom):
    t, c = geom["type"], geom["coordinates"]
    if t == "LineString":
        return [c]
    if t == "MultiLineString":
        return c
    if t == "Polygon":
        return [c[0]]
    if t == "MultiPolygon":
        return [p[0] for p in c]
    return []


def clip(line):
    """Split a line into the runs that are inside a range (keeping one point either side)."""
    runs, cur = [], []
    for i, p in enumerate(line):
        near = inside(p) or (i and inside(line[i - 1])) or (i + 1 < len(line) and inside(line[i + 1]))
        if near:
            cur.append(p)
        elif cur:
            runs.append(cur); cur = []
    if cur:
        runs.append(cur)
    return [r for r in runs if len(r) > 1]


def pack(features, keep=lambda f: True):
    out = []
    for f in features:
        if not keep(f["properties"]):
            continue
        for line in lines(f["geometry"]):
            for run in clip(line):
                if run[0] == run[-1] and len(run) > 3:  # a closed ring: simplify each half, or it collapses to a point
                    m = len(run) // 2
                    pts = simplify(run[:m + 1])[:-1] + simplify(run[m:])
                else:
                    pts = simplify(run)
                flat = [round(v * 10) for p in pts for v in p[:2]]
                if len(flat) >= 4:
                    out.append(flat)
    return out


def load(name):
    return json.loads((HERE / "dev" / f"ne_50m_{name}.geojson").read_text())["features"]


geo = {
    "borders": pack(load("admin_0_boundary_lines_land")),
    "states": pack(load("admin_1_states_provinces_lines"),
                   lambda p: (p.get("adm0_a3") or p.get("ADM0_A3")) in ("USA", "CAN")),
    "rivers": pack(load("rivers_lake_centerlines"), lambda p: p.get("scalerank", 9) <= 6),
    "lakes": pack(load("lakes"), lambda p: p.get("scalerank", 9) <= 4),
}
js = ("// Generated by make_geo.py from Natural Earth 1:50m (public domain). Do not edit.\n"
      "// Lines as flat [lon, lat, ...] in tenths of a degree; lakes are closed outlines.\n"
      f"window.GEO = {json.dumps(geo, separators=(',', ':'))};\n")
(HERE / "static" / "geo.js").write_text(js)
print("geo.js:", {k: len(v) for k, v in geo.items()}, f"{len(js) // 1024} KB")
